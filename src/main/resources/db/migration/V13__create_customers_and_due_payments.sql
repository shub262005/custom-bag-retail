-- Customer management and credit / due payments tracking for sales
-- =============================================================================

-- 1. Create customers table
CREATE TABLE IF NOT EXISTS customers (
    customer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    phone VARCHAR(20) NOT NULL,
    email VARCHAR(150),
    address VARCHAR(500),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT chk_customer_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

CREATE INDEX IF NOT EXISTS idx_customers_phone ON customers (phone);
CREATE INDEX IF NOT EXISTS idx_customers_name ON customers (LOWER(name));
CREATE INDEX IF NOT EXISTS idx_customers_status ON customers (status);

-- 2. Add customer and due payment tracking columns to sales table
ALTER TABLE sales ADD COLUMN IF NOT EXISTS customer_id BIGINT;
ALTER TABLE sales ADD COLUMN IF NOT EXISTS paid_amount NUMERIC(12, 2) NOT NULL DEFAULT 0.00;
ALTER TABLE sales ADD COLUMN IF NOT EXISTS due_amount NUMERIC(12, 2) NOT NULL DEFAULT 0.00;
ALTER TABLE sales ADD COLUMN IF NOT EXISTS payment_status VARCHAR(20) NOT NULL DEFAULT 'PAID';

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'fk_sales_customer'
    ) THEN
        ALTER TABLE sales ADD CONSTRAINT fk_sales_customer
            FOREIGN KEY (customer_id) REFERENCES customers(customer_id) ON DELETE SET NULL;
    END IF;
END $$;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'chk_sales_payment_status'
    ) THEN
        ALTER TABLE sales ADD CONSTRAINT chk_sales_payment_status
            CHECK (payment_status IN ('PAID', 'PARTIALLY_PAID', 'UNPAID'));
    END IF;
END $$;

-- Populate existing sales records with paid_amount = grand_total and payment_status = 'PAID'
UPDATE sales
SET paid_amount = grand_total,
    due_amount = 0.00,
    payment_status = 'PAID'
WHERE paid_amount = 0.00 AND grand_total > 0;

CREATE INDEX IF NOT EXISTS idx_sales_customer_id ON sales (customer_id);
CREATE INDEX IF NOT EXISTS idx_sales_payment_status ON sales (payment_status);
CREATE INDEX IF NOT EXISTS idx_sales_due_amount ON sales (due_amount);

-- 3. Create customer repayments table
CREATE TABLE IF NOT EXISTS customer_repayments (
    repayment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL,
    sale_id BIGINT,
    amount NUMERIC(12, 2) NOT NULL,
    payment_method VARCHAR(30) NOT NULL,
    repayment_date DATE NOT NULL,
    notes VARCHAR(500),
    received_by VARCHAR(100),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT fk_repayment_customer FOREIGN KEY (customer_id) REFERENCES customers(customer_id) ON DELETE RESTRICT,
    CONSTRAINT fk_repayment_sale FOREIGN KEY (sale_id) REFERENCES sales(sale_id) ON DELETE SET NULL,
    CONSTRAINT chk_repayment_amount CHECK (amount > 0),
    CONSTRAINT chk_repayment_method CHECK (payment_method IN ('CASH', 'UPI', 'CARD', 'BANK_TRANSFER', 'OTHER'))
);

CREATE INDEX IF NOT EXISTS idx_repayments_customer_id ON customer_repayments (customer_id);
CREATE INDEX IF NOT EXISTS idx_repayments_sale_id ON customer_repayments (sale_id);
CREATE INDEX IF NOT EXISTS idx_repayments_date ON customer_repayments (repayment_date);
